#!/usr/bin/env node
/* Copies the verified portfolio snapshot from the terminal.sanketmuchhala.com
   repository into a plain script, so CloudOS stays build-free and still works
   when index.html is opened directly from disk.

   Usage: node scripts/sync-portfolio.mjs [path/to/portfolio.generated.json]
   Default source: ../terminal.sanketmuchhala.com/src/content/portfolio.generated.json */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.argv[2] || process.env.PORTFOLIO_JSON || resolve(root, '../terminal.sanketmuchhala.com/src/content/portfolio.generated.json'));
const data = JSON.parse(readFileSync(source, 'utf8'));

for (const key of ['person', 'projects', 'skills', 'experience', 'relationships', 'links']) {
  if (!data[key] || (Array.isArray(data[key]) && !data[key].length && key !== 'relationships')) {
    console.error(`Refusing to sync: "${key}" is missing or empty in ${source}.`);
    process.exit(1);
  }
}

const out = resolve(root, 'js/portfolio/data.js');
writeFileSync(out, `/* Generated by scripts/sync-portfolio.mjs from terminal.sanketmuchhala.com
   (src/content/portfolio.generated.json). Do not edit by hand; re-run the script. */
window.PORTFOLIO_DATA = ${JSON.stringify(data)};
`);
console.log(`Wrote ${out}: ${data.projects.length} projects, ${data.skills.length} skills, ${data.experience.length} roles, ${data.relationships.length} relationships.`);
